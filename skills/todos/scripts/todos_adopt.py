"""Adopt mode: split an existing sprawling TODO.md into monthly archives.

This runs once, against a file that holds months of decisions nobody can
reconstruct from anything but the prose itself -- why a call went the way it
did, what was measured, which commit carried it. Losing a section here is
not a formatting slip, it is losing the reasoning. So the split proves
itself by comparison (is this exact text still there?) rather than by count
(a line tally is satisfied by the wrong lines) before anything touches disk.

Run:  python3 scripts/todos_adopt.py TODO.md out_dir/
"""
import io
import os
import re
import sys

HEADING_RE = re.compile(r"^## .*$", re.MULTILINE)
DATE_RE = re.compile(r"20\d\d-\d\d-\d\d")

ARCHIVE_HEADER = """# TODO archive -- {month}

Generated by `todos_adopt.py`, which split the original sprawling TODO.md
by month. Nothing below has been edited, reformatted, or reworded -- every
section is byte-identical to its "## " section in the file it came from.

"""


def split(text):
    """Return one (month, heading, body) tuple per "## " section in text.

    `heading` is the full heading line (including its "## " marker), with no
    trailing newline. `body` is everything between that heading line and the
    next "## " heading (or end of file), untouched -- this is what later
    gets byte-compared, so it must not be re-stripped or re-wrapped.

    The month comes from the first 20\\d\\d-\\d\\d-\\d\\d in the section's own
    heading. A heading with no date inherits the month of the section above
    it: these files are written newest-first, so an undated section is part
    of whatever dated block it trails.
    """
    matches = list(HEADING_RE.finditer(text))
    sections = []
    prev_month = None
    for i, m in enumerate(matches):
        heading = m.group(0)
        body_start = m.end()
        body_end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        body = text[body_start:body_end]

        date_match = DATE_RE.search(heading)
        if date_match:
            month = date_match.group(0)[:7]
        elif prev_month is not None:
            month = prev_month
        else:
            # No date on the very first section and nothing above it to
            # inherit from -- shouldn't happen in a newest-first file, but
            # don't crash the split over it.
            month = "undated"

        sections.append((month, heading, body))
        prev_month = month

    return sections


def verify_split(text, archives):
    """Return failure messages for sections that did not survive the split.

    This checks section loss only -- content `write_archives` promised to
    carry into an archive and did not. That is data already gone: the
    archive was supposed to hold it and doesn't, so `write_archives` must
    refuse and this is what it asserts on. Content before the first "## "
    heading is a different kind of problem (see `check_preamble`): it is
    not lost, still sitting in the source file the operator is about to
    overwrite, so it must not stop the write -- warn, don't refuse. Do not
    fold that check back in here; the two failure modes need different
    responses from the caller, which is exactly why they're two functions.

    Checked against `archives[month]` specifically -- not against any
    archive that happens to contain a match -- because a section landing in
    the wrong month's file is exactly the kind of silent misfile this exists
    to catch, and it must not pass just because the text is *somewhere*.

    Plain containment ("is this body in the archive text?") is not enough:
    if two sections in the same month have the same body -- or one body is a
    literal substring of another's -- containment can find a single leftover
    occurrence and call every copy present, even though one was dropped.
    That is a false all-clear on the exact check `write_archives` trusts
    before an irreversible overwrite, so this counts instead of just
    checking membership: for each month, and for each distinct section
    among that month's sections, the archive must contain at least as many
    occurrences as the source has.

    Each section is keyed on `heading + body` -- exactly the byte sequence
    `write_archives` emits per section -- not on body alone. Keying on body
    alone has a second failure mode beyond duplicate/nested bodies: a body
    that is empty, or empty-looking (whitespace only, which is the ordinary
    shape of two adjacent "## " headings with nothing between them), is
    either impossible to verify by presence or matches almost anywhere.
    Folding the heading into the key removes the whole class of problem
    instead of special-casing each shape of it -- a heading line is never
    empty or generic the way a body can be.

    Occurrences are found longest-key-first, and each match is masked out
    of a working copy of the archive text before moving on. Without that, a
    shorter key that is a literal substring of a longer one would be "found"
    inside the longer key's own occurrence even when the section it belongs
    to was never written -- the mask makes that occurrence unavailable to
    anything but the key it actually belongs to.
    """
    missing = []

    sections = split(text)
    by_month = {}
    for month, heading, body in sections:
        by_month.setdefault(month, []).append((heading, body))

    for month, items in by_month.items():
        archive_text = archives.get(month, "")
        working = archive_text

        needed_counts = {}
        headings_by_key = {}
        for heading, body in items:
            key = heading + body
            needed_counts[key] = needed_counts.get(key, 0) + 1
            headings_by_key.setdefault(key, []).append(heading)

        # Longest first, so a shorter key that is a literal substring of a
        # longer one is checked against what's left *after* the longer
        # key's own occurrence has been claimed and masked out.
        for key in sorted(needed_counts, key=len, reverse=True):
            needed = needed_counts[key]
            actual = 0
            start = 0
            while True:
                idx = working.find(key, start)
                if idx == -1:
                    break
                actual += 1
                working = working[:idx] + ("\0" * len(key)) + working[idx + len(key):]
                start = idx + len(key)
            if actual < needed:
                headings = ", ".join(headings_by_key[key])
                missing.append(
                    f"{month}: a section occurs {needed} time(s) in the "
                    f"source but only {actual} time(s) in the {month} archive "
                    f"-- {headings}"
                )
    return missing


def check_preamble(text):
    """Return a warning message, or None, for content before the first
    "## " heading.

    Unlike a missing section, this content is not lost -- it is exactly
    where it has always been, in the `TODO.md` the operator is about to
    overwrite by hand in step 4 of adopt mode. It just never becomes part
    of any archive, because `split()`/`verify_split()` only see "## "
    sections. That is a "don't forget" problem, not a "something is
    already gone" problem, so it must be loud, not blocking.
    """
    heading_matches = list(HEADING_RE.finditer(text))
    preamble_end = heading_matches[0].start() if heading_matches else len(text)
    preamble = text[:preamble_end]
    if not preamble.strip():
        return None
    line_count = len(preamble.splitlines())
    first_line = next((ln for ln in preamble.splitlines() if ln.strip()), "")
    return (
        f"{line_count} line(s) before the first \"## \" heading belong to "
        f"no section and will NOT be carried into any archive -- place "
        f"this content by hand before TODO.md is overwritten -- "
        f"starts: {first_line.strip()!r}"
    )


def write_archives(text, out_dir):
    """Split `text` by month and write one archive file per month.

    Builds every archive's full text in memory first, asks verify_split to
    check it against the original, and asserts the answer is empty before
    writing a single byte -- a refusal must not leave a half-written
    directory behind.

    A dropped section is data already lost -- write_archives refuses and
    writes nothing. A non-blank preamble is not lost -- it is still in
    `text`, which the operator overwrites by hand afterward -- so it is
    reported loudly (a WARNING line on stderr, printed by write_archives
    itself so it reaches any caller, not only `main()`) but does not block
    the write. Same underlying worry, deliberately different response,
    because conflating them either lets real loss through quietly or
    refuses to write files that are completely correct. The return value
    stays `dict[str, int]` -- month to section count, as documented --
    rather than growing a second shape for this; a caller that needs the
    warning text itself calls `check_preamble(text)` directly.
    """
    sections = split(text)

    by_month = {}
    order = []
    for month, heading, body in sections:
        if month not in by_month:
            by_month[month] = []
            order.append(month)
        by_month[month].append((heading, body))

    archives = {}
    counts = {}
    for month in order:
        parts = [ARCHIVE_HEADER.format(month=month)]
        for heading, body in by_month[month]:
            parts.append(heading + body)
        archives[month] = "".join(parts)
        counts[month] = len(by_month[month])

    missing = verify_split(text, archives)
    assert not missing, (
        "refusing to write archives -- these sections are not byte-identical "
        "in their archive, nothing was written: " + ", ".join(missing)
    )

    os.makedirs(out_dir, exist_ok=True)
    for month, content in archives.items():
        with io.open(os.path.join(out_dir, month + ".md"), "w", encoding="utf-8") as f:
            f.write(content)

    preamble_warning = check_preamble(text)
    if preamble_warning:
        print(f"WARNING: {preamble_warning}", file=sys.stderr)

    return counts


def main(argv):
    if len(argv) != 3:
        print("usage: todos_adopt.py TODO.md out_dir/", file=sys.stderr)
        return 2
    src_path, out_dir = argv[1], argv[2]
    with io.open(src_path, encoding="utf-8") as f:
        text = f.read()
    counts = write_archives(text, out_dir)
    for month in sorted(counts):
        print(f"{month}: {counts[month]} sections")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
